#!/usr/bin/env python3
"""Generates the files that depend on the struct layout of c_api/include/hoverhere/sim_types.h:

  c_api/src/layout_table.inc
      sizeof() of every struct and offsetof() of every member as the C compiler sees them (read through hh_get_layout_entry).
  HoverHere/Assets/Scripting/Native/HoverHereNative.Structs.g.cs
      the blittable C# mirror structs (unsafe fixed buffers for arrays), same member names as the C structs.

The C# interop check (bindings/csharp/HoverHere.Interop.Check) compares Marshal.SizeOf / Marshal.OffsetOf of the C# structs with the
table of the C compiler, so a wrong type, a missing field or different padding is found without running the simulation.

usage: py -3 tools/gen_layout_table.py [--check]     (--check only verifies that the checked-in files are up to date)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "c_api" / "include" / "hoverhere" / "sim_types.h"
TABLE_OUTPUT = ROOT / "c_api" / "src" / "layout_table.inc"
CSHARP_OUTPUT = ROOT.parent / "HoverHere" / "Assets" / "Scripting" / "Native" / "HoverHereNative.Structs.g.cs"

STRUCT = re.compile(r"typedef\s+struct\s+(\w+)\s*\{(.*?)\}\s*(\w+)\s*;", re.S)
MEMBER = re.compile(r"^([A-Za-z_][\w\s\*]*?)[\s\*](\w+)((?:\[[^\]]+\])*)\s*;\s*$")
DEFINE = re.compile(r"^#define\s+(HH_\w+)\s+(\d+)\b", re.M)

PRIMITIVE = {  # C type -> (C# type, size and alignment)
    "double": ("double", 8),
    "int32_t": ("int", 4),
    "uint32_t": ("uint", 4),
    "uint64_t": ("ulong", 8),
}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse():
    raw = HEADER.read_text(encoding="utf-8")
    defines = {name: int(value) for name, value in DEFINE.findall(strip_comments(raw))}
    text = strip_comments(raw)
    structs = []
    for match in STRUCT.finditer(text):
        tag, body, name = match.groups()
        assert tag == name, f"struct tag {tag} differs from typedef name {name}"
        members = []
        for line in body.split("\n"):
            line = line.strip()
            if not line:
                continue
            member = MEMBER.match(line)
            if member is None:
                raise SystemExit(f"cannot parse member '{line}' of {name}")
            ctype = " ".join(member.group(1).split())
            dims = [int(d) if d.isdigit() else defines[d] for d in re.findall(r"\[([^\]]+)\]", member.group(3))]
            members.append((ctype, member.group(2), dims))
        structs.append((name, members))
    return structs


def layout(structs):
    """size and alignment of every struct with natural alignment of the members"""
    info = {}
    for name, members in structs:
        offset = 0
        align = 1
        for ctype, _, dims in members:
            if ctype in PRIMITIVE:
                size = PRIMITIVE[ctype][1]
                a = size
            else:
                size, a = info[ctype]
            count = 1
            for d in dims:
                count *= d
            offset = (offset + a - 1) // a * a
            offset += size * count
            align = max(align, a)
        info[name] = ((offset + align - 1) // align * align, align)
    return info


def table(structs) -> str:
    lines = ["/* Generated by tools/gen_layout_table.py from hoverhere/sim_types.h. DO NOT EDIT. */"]
    for name, members in structs:
        lines.append(f"HH_LAYOUT_SIZE({name})")
        for _, member, _ in members:
            lines.append(f"HH_LAYOUT_OFFSET({name}, {member})")
    return "\n".join(lines) + "\n"


def csharp_name(name: str) -> str:
    return "Native" + "".join(part.capitalize() for part in name.removeprefix("hh_").split("_"))


def csharp(structs) -> str:
    info = layout(structs)
    out = [
        "// <auto-generated>",
        "// Generated by tools/gen_layout_table.py from c_api/include/hoverhere/sim_types.h. DO NOT EDIT.",
        "// Blittable mirrors of the C structs of hoverhere.dll (same member names, same layout, checked by HoverHere.Interop.Check).",
        "// </auto-generated>",
        "using System.Runtime.InteropServices;",
        "",
        "namespace HoverHere.Native",
        "{",
        "    public static class NativeConstants",
        "    {",
    ]
    defines = {name: value for name, value in DEFINE.findall(strip_comments(HEADER.read_text(encoding="utf-8")))}
    for name, value in defines.items():
        out.append(f"        public const int {name} = {value};")
    out += ["    }", ""]
    for name, members in structs:
        cs = csharp_name(name)
        out.append("    [StructLayout(LayoutKind.Sequential)]")
        out.append(f"    public unsafe struct {cs}")
        out.append("    {")
        raw_accessors = []
        for ctype, member, dims in members:
            count = 1
            for d in dims:
                count *= d
            if ctype in PRIMITIVE:
                cs_type = PRIMITIVE[ctype][0]
                if dims:
                    out.append(f"        public fixed {cs_type} {member}[{count}];" + (f"  // [{']['.join(map(str, dims))}]" if len(dims) > 1 else ""))
                else:
                    out.append(f"        public {cs_type} {member};")
            else:
                nested = csharp_name(ctype)
                if dims:
                    size = info[ctype][0]
                    out.append(f"        public fixed byte {member}__raw[{count * size}];  // {count} x {nested}, see Get_{member}")
                    raw_accessors.append((member, nested, count))
                else:
                    out.append(f"        public {nested} {member};")
        for member, nested, count in raw_accessors:
            out.append("")
            out.append(f"        public {nested} Get_{member}(int index)")
            out.append("        {")
            out.append(f"            if ((uint)index >= {count}) throw new System.IndexOutOfRangeException();")
            out.append(f"            fixed (byte* p = {member}__raw) return (({nested}*)p)[index];")
            out.append("        }")
        out.append("    }")
        out.append("")
    out.append("}")
    return "\n".join(out) + "\n"


def write_or_check(path: pathlib.Path, content: str, check: bool) -> int:
    if check:
        if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != content:
            print(f"{path} is out of date, run tools/gen_layout_table.py", file=sys.stderr)
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path}")
    return 0


def main() -> int:
    structs = parse()
    check = "--check" in sys.argv
    status = write_or_check(TABLE_OUTPUT, table(structs), check)
    status |= write_or_check(CSHARP_OUTPUT, csharp(structs), check)
    return status


if __name__ == "__main__":
    sys.exit(main())
